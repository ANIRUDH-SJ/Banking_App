CREATE TABLE bank (
    bank_id      NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    bank_code    VARCHAR2(20 CHAR)  NOT NULL,
    legal_name   VARCHAR2(200 CHAR) NOT NULL,
    display_name VARCHAR2(200 CHAR) NOT NULL,
    is_active    CHAR(1 CHAR) DEFAULT 'Y' NOT NULL,
    created_at   TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at   TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT pk_bank PRIMARY KEY (bank_id),
    CONSTRAINT uq_bank_code UNIQUE (bank_code),
    CONSTRAINT ck_bank_code_uppercase CHECK (bank_code = UPPER(bank_code)),
    CONSTRAINT ck_bank_is_active CHECK (is_active IN ('Y', 'N'))
);

CREATE TABLE branch (
    branch_id      NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    bank_id        NUMBER(19) NOT NULL,
    branch_code    VARCHAR2(20 CHAR)  NOT NULL,
    branch_name    VARCHAR2(200 CHAR) NOT NULL,
    ifsc_code      VARCHAR2(11 CHAR)  NOT NULL,
    email          VARCHAR2(254 CHAR),
    phone_number   VARCHAR2(30 CHAR),
    address_line_1 VARCHAR2(200 CHAR) NOT NULL,
    address_line_2 VARCHAR2(200 CHAR),
    city           VARCHAR2(100 CHAR) NOT NULL,
    state          VARCHAR2(100 CHAR) NOT NULL,
    postal_code    VARCHAR2(20 CHAR)  NOT NULL,
    is_active      CHAR(1 CHAR) DEFAULT 'Y' NOT NULL,
    created_at     TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at     TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT pk_branch PRIMARY KEY (branch_id),
    CONSTRAINT fk_branch_bank FOREIGN KEY (bank_id)
        REFERENCES bank (bank_id),
    CONSTRAINT uq_branch_bank_code UNIQUE (bank_id, branch_code),
    CONSTRAINT uq_branch_ifsc_code UNIQUE (ifsc_code),
    CONSTRAINT ck_branch_code_uppercase CHECK (branch_code = UPPER(branch_code)),
    CONSTRAINT ck_branch_ifsc_uppercase CHECK (ifsc_code = UPPER(ifsc_code)),
    CONSTRAINT ck_branch_ifsc_format CHECK (
        REGEXP_LIKE(ifsc_code, '^[A-Z]{4}0[A-Z0-9]{6}$')
    ),
    CONSTRAINT ck_branch_is_active CHECK (is_active IN ('Y', 'N'))
);


CREATE OR REPLACE TRIGGER trg_bank_set_updated_at
BEFORE UPDATE ON bank
FOR EACH ROW
BEGIN
    :NEW.updated_at := SYSTIMESTAMP;
END;
/

CREATE OR REPLACE TRIGGER trg_branch_set_updated_at
BEFORE UPDATE ON branch
FOR EACH ROW
BEGIN
    :NEW.updated_at := SYSTIMESTAMP;
END;
/

CREATE TABLE bank_account (
    account_id         NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    branch_id          NUMBER(19) NOT NULL,
    account_number     VARCHAR2(20 CHAR) NOT NULL,
    account_type       VARCHAR2(20 CHAR) NOT NULL,
    currency_code      CHAR(3 CHAR) DEFAULT 'INR' NOT NULL,
    account_status     VARCHAR2(20 CHAR) DEFAULT 'PENDING' NOT NULL,
    current_balance    NUMBER(19,4) DEFAULT 0 NOT NULL,
    available_balance  NUMBER(19,4) DEFAULT 0 NOT NULL,
    opened_at          TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    closed_at          TIMESTAMP(6),
    created_at         TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at         TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT pk_bank_account PRIMARY KEY (account_id),
    CONSTRAINT fk_bank_account_branch FOREIGN KEY (branch_id)
        REFERENCES branch (branch_id),
    CONSTRAINT uq_bank_account_number UNIQUE (account_number),
    CONSTRAINT ck_bank_account_type CHECK (
        account_type IN ('SAVINGS', 'CURRENT')
    ),
    CONSTRAINT ck_bank_account_currency CHECK (currency_code = UPPER(currency_code)),
    CONSTRAINT ck_bank_account_status CHECK (
        account_status IN ('PENDING', 'ACTIVE', 'FROZEN', 'CLOSED')
    ),
    CONSTRAINT ck_bank_account_number CHECK (REGEXP_LIKE(account_number, '^[0-9]{10,20}$')),
    CONSTRAINT ck_bank_account_balances CHECK (
        current_balance >= 0
        AND available_balance >= 0
        AND available_balance <= current_balance
    ),
    CONSTRAINT ck_bank_account_closed CHECK (
        (account_status = 'CLOSED' AND closed_at IS NOT NULL)
        OR account_status <> 'CLOSED'
    )
);

CREATE TABLE account_holder (
    account_id       NUMBER(19) NOT NULL,
    customer_id      NUMBER(19) NOT NULL,
    holder_type      VARCHAR2(20 CHAR) DEFAULT 'PRIMARY' NOT NULL,
    is_active        CHAR(1 CHAR) DEFAULT 'Y' NOT NULL,
    joined_at        TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT pk_account_holder PRIMARY KEY (account_id, customer_id),
    CONSTRAINT fk_account_holder_account FOREIGN KEY (account_id)
        REFERENCES bank_account (account_id),
    CONSTRAINT ck_account_holder_type CHECK (
        holder_type IN ('PRIMARY', 'JOINT')
    ),
    CONSTRAINT ck_account_holder_active CHECK (is_active IN ('Y', 'N'))
);

CREATE INDEX ix_account_holder_customer ON account_holder (customer_id);

